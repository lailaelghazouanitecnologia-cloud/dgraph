/// Fulltext tokenizer - word-based with stopword removal
#[derive(Clone, Debug, Default)]
pub struct FulltextTokenizer;

impl FulltextTokenizer {
    /// Basic English stopwords
    const STOPWORDS: &'static [&'static str] = &[
        "a", "an", "and", "are", "as", "at", "be", "by", "for", "from", "has", "he", "in", "is",
        "it", "its", "of", "on", "that", "the", "to", "was", "were", "will", "with",
    ];

    fn is_stopword(word: &str) -> bool {
        Self::STOPWORDS.binary_search(&word).is_ok()
    }
}

impl Tokenizer for FulltextTokenizer {
    fn name(&self) -> &'static str {
        "fulltext"
    }

    fn id(&self) -> TokenizerId {
        TokenizerId::Fulltext
    }

    fn is_sortable(&self) -> bool {
        false
    }

    fn is_lossy(&self) -> bool {
        true
    }

    fn tokenize_string(&self, value: &str) -> Vec<Token> {
        let mut seen = HashSet::new();
        let mut tokens = Vec::new();

        for word in value.split(|c: char| !c.is_alphanumeric()) {
            let normalized = word.to_lowercase();
            if normalized.is_empty() || Self::is_stopword(&normalized) {
                continue;
            }
            if seen.insert(normalized.clone()) {
                tokens.push(Token::from_str(self.id(), &normalized));
            }
        }

        tokens
    }
}

/// Registry of tokenizers by name
pub struct TokenizerRegistry {
    tokenizers: Vec<Box<dyn Tokenizer>>,
}

impl Default for TokenizerRegistry {
    fn default() -> Self {
        Self::new()
    }
}

impl TokenizerRegistry {
    /// Create registry with all built-in tokenizers
    #[must_use]
    pub fn new() -> Self {
        Self {
            tokenizers: vec![
                Box::new(ExactTokenizer),
                Box::new(TermTokenizer),
                Box::new(TrigramTokenizer),
                Box::new(HashTokenizer),
                Box::new(IntTokenizer),
                Box::new(FloatTokenizer),
                Box::new(BoolTokenizer),
                Box::new(FulltextTokenizer),
            ],
        }
    }

    /// Get tokenizer by name
    #[must_use]
    pub fn get(&self, name: &str) -> Option<&dyn Tokenizer> {
        self.tokenizers
            .iter()
            .find(|t| t.name() == name)
            .map(AsRef::as_ref)
    }

    /// Get tokenizer by ID
    #[must_use]
    pub fn get_by_id(&self, id: TokenizerId) -> Option<&dyn Tokenizer> {
        self.tokenizers
            .iter()
            .find(|t| t.id() == id)
            .map(AsRef::as_ref)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exact_tokenizer() {
        let tok = ExactTokenizer;
        let tokens = tok.tokenize_string("Hello World");
        assert_eq!(tokens.len(), 1);
        assert_eq!(tokens[0].data.as_ref(), b"Hello World");
        assert_eq!(tokens[0].id, TokenizerId::Exact);
    }

    #[test]
    fn term_tokenizer() {
        let tok = TermTokenizer;
        let tokens = tok.tokenize_string("Hello World");
        assert_eq!(tokens.len(), 2);
        assert_eq!(tokens[0].data.as_ref(), b"hello");
        assert_eq!(tokens[1].data.as_ref(), b"world");
    }

    #[test]
    fn trigram_tokenizer() {
        let tok = TrigramTokenizer;
        let tokens = tok.tokenize_string("hello");
        // "hel", "ell", "llo"
        assert_eq!(tokens.len(), 3);
    }

    #[test]
    fn hash_tokenizer() {
        let tok = HashTokenizer;
        let tokens = tok.tokenize_string("test");
        assert_eq!(tokens.len(), 1);
        assert_eq!(tokens[0].data.len(), 8);
    }

    #[test]
    fn int_tokenizer() {
        let tok = IntTokenizer;

        // Positive numbers
        let t1 = tok.tokenize_int(100);
        let t2 = tok.tokenize_int(200);
        assert!(t1[0].data > t2[0].data || t1[0].data < t2[0].data); // Just check different

        // Verify sortable ordering: -100 < 0 < 100
        let neg = tok.tokenize_int(-100);
        let zero = tok.tokenize_int(0);
        let pos = tok.tokenize_int(100);
        assert!(neg[0].data < zero[0].data);
        assert!(zero[0].data < pos[0].data);
    }

    #[test]
    fn float_tokenizer() {
        let tok = FloatTokenizer;
        let neg = tok.tokenize_float(-1.0);
        let zero = tok.tokenize_float(0.0);
        let pos = tok.tokenize_float(1.0);
        assert!(neg[0].data < zero[0].data);
        assert!(zero[0].data < pos[0].data);
    }

    #[test]
    fn bool_tokenizer() {
        let tok = BoolTokenizer;
        let t = tok.tokenize_bool(true);
        let f = tok.tokenize_bool(false);
        assert_eq!(t[0].data.as_ref(), &[1]);
        assert_eq!(f[0].data.as_ref(), &[0]);
    }

    #[test]
    fn fulltext_tokenizer() {
        let tok = FulltextTokenizer;
        let tokens = tok.tokenize_string("The quick brown fox");
        // "the" is a stopword
        assert_eq!(tokens.len(), 3);
        assert!(tokens.iter().any(|t| t.data.as_ref() == b"quick"));
        assert!(tokens.iter().any(|t| t.data.as_ref() == b"brown"));
        assert!(tokens.iter().any(|t| t.data.as_ref() == b"fox"));
    }

    #[test]
    fn token_encode_decode() {
        let token = Token::from_str(TokenizerId::Exact, "test");
        let encoded = token.encode();
        let decoded = Token::decode(&encoded).unwrap();
        assert_eq!(decoded.id, TokenizerId::Exact);
        assert_eq!(decoded.data.as_ref(), b"test");
    }

    #[test]
    fn tokenizer_registry() {
        let registry = TokenizerRegistry::new();
        assert!(registry.get("exact").is_some());
        assert!(registry.get("term").is_some());
        assert!(registry.get("unknown").is_none());
        assert!(registry.get_by_id(TokenizerId::Exact).is_some());
    }
}
